from __future__ import annotations

from ._shared import LANGUAGE_RULES_AR, Difficulty


def _qwen_output_format_section(context: str) -> str:
    return f"""أخرج النتائج فقط بصيغة JSON المطابقة للمخطط التالي دون أي شرح أو تعليق خارج JSON.

{{
  "mcq": [
    {{
      "q": "",
      "options": ["", "", "", ""],
      "answer": "",
      "solution": "",
      "type": "computational | analytical | applied | conceptual",
      "difficulty": "medium | hard"
    }}
  ]
}}

UPLOADED DOCUMENT:
{context}"""


def build_qwen_prompt(
    context: str,
    difficulty: Difficulty,
    num_questions: int | None = None,
) -> str:
    del difficulty, num_questions
    return f"""أنت خبير في تصميم الاختبارات الجامعية باللغة العربية.

ستحصل على نص أو جزء من محاضرة جامعية. مهمتك هي استخراج أفضل الأسئلة الممكنة من هذا المحتوى فقط.

{LANGUAGE_RULES_AR}

========================
الهدف
========================

ولّد بين 5 و10 أسئلة فقط.

لا تهدف إلى زيادة العدد، بل إلى اختيار الأسئلة ذات القيمة التعليمية الأعلى فقط.

إذا لم يكن المحتوى يحتوي على أفكار كافية فلا تخترع أسئلة إضافية.

========================
ترتيب الأولوية
========================

اختر الأسئلة وفق الترتيب التالي:

1- أسئلة تحليلية تتطلب الفهم والاستنتاج وربط المفاهيم.
2- أسئلة حسابية أو تطبيقية تعتمد على معادلات أو كود أو جداول أو قيم موجودة فعلاً في المستند.
3- أسئلة تفسير نتائج الكود أو تفسير المخرجات.
4- أسئلة مفاهيمية مهمة تقيس الفهم الحقيقي.
5- أسئلة تعريفية فقط إذا كان المفهوم أساسياً جداً.

========================
ممنوع تماماً
========================

لا تخترع أي رقم أو قيمة أو معادلة أو جدول أو اسم متغير غير موجود في المستند.

لا تؤلف مثالاً من عندك.

لا تكتب:
"إذا افترضنا..."

ولا:

"لنفترض..."

ولا:

"إذا كانت البيانات تحتوي..."

إلا إذا كان ذلك مذكوراً صراحة داخل المستند.

لا تسأل عن أشياء لا يستطيع الطالب معرفتها من النص.

لا تنتج أسئلة تعتمد على التخمين.

لا تكرر نفس الفكرة بأكثر من سؤال.

لا تعيد صياغة السؤال نفسه بصياغات مختلفة.

========================
الأسئلة الحسابية
========================

لا تُنشئ سؤالاً حسابياً إلا إذا احتوى المستند فعلاً على:

- أرقام
- معادلات
- أبعاد Tensor
- Shapes
- Parameters
- Epochs
- Batch Size
- Learning Rate
- نتائج تنفيذ
- جداول
- أكواد قابلة للتحليل

إذا لم تتوفر هذه المعلومات فلا تُنشئ أي سؤال حسابي.

لا تجعل أكثر من 40% من الأسئلة حسابية. إذا وُجدت عدة قيم رقمية في المستند، اختر أهم سؤال حسابي فقط، وركّز بقية الأسئلة على تفسير النتائج، وتحليل الكود، وسبب استخدام الخوارزميات، والمقارنة بين الأساليب.

========================
الأسئلة التحليلية
========================

فضّل الأسئلة التي تبدأ مثل:

لماذا...
ما سبب...
ما أثر...
ما النتيجة المتوقعة...
ما الفرق بين...
أي الخيارات أدق...
ما الذي سيحدث إذا...
كيف يؤثر...

ولا تكتفِ بأسئلة الحفظ المباشر.

========================
جودة الخيارات
========================

كل سؤال MCQ يجب أن يحتوي على:

- أربعة خيارات فقط.
- مشتتات منطقية وقريبة من الإجابة الصحيحة.
- عدم وجود خيار واضح جداً أو مضحك.
- عدم تكرار الخيارات.

========================
التفسير
========================

التفسير يجب أن يوضح لماذا الإجابة صحيحة اعتماداً على المستند فقط.

لا تضف معلومات خارج النص.

========================
مستوى الصعوبة
========================

اجعل معظم الأسئلة بين Medium وHard.

لا تنتج أسئلة Easy إلا إذا كان المفهوم أساسياً جداً.

========================
عدد الأسئلة
========================

ولّد من 5 إلى 10 أسئلة فقط.

إذا لم تجد سوى 5 أسئلة قوية فتوقف.

لا تملأ العدد بأسئلة ضعيفة.

الجودة أهم من الكمية.

========================
المخرجات
========================

{_qwen_output_format_section(context)}"""
